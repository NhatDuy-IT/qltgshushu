export function uid(prefix = 'id') {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`;
}

export function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function toDateKey(date = new Date()) {
  const d = typeof date === 'string' ? new Date(date) : date;
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

export function addDays(baseDate, offsetDays) {
  const d = new Date(baseDate);
  d.setDate(d.getDate() + offsetDays);
  return d;
}

export function parseDateTime(dateStr, timeStr = '09:00') {
  if (!dateStr) return null;
  const [y, m, d] = dateStr.split('-').map(Number);
  const [hh, mm] = (timeStr || '09:00').split(':').map(Number);
  return new Date(y, (m || 1) - 1, d || 1, hh || 0, mm || 0, 0, 0);
}

export function formatDateShort(dateStr) {
  if (!dateStr) return '';
  const [, m, d] = dateStr.split('-');
  return `${d}/${m}`;
}

export function formatDateFullVi(date = new Date()) {
  const d = typeof date === 'string' ? parseDateTime(date) : date;
  const days = ['Chủ Nhật', 'Thứ Hai', 'Thứ Ba', 'Thứ Tư', 'Thứ Năm', 'Thứ Sáu', 'Thứ Bảy'];
  return `${days[d.getDay()]}, ${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`;
}

export function formatMonthYearVi(year, monthIndex) {
  return `Tháng ${monthIndex + 1}, ${year}`;
}

export function formatVND(amount) {
  const n = Number(amount) || 0;
  return new Intl.NumberFormat('vi-VN').format(Math.round(n)) + ' ₫';
}

export function formatVNDShort(amount) {
  const n = Number(amount) || 0;
  if (Math.abs(n) >= 1_000_000) {
    return (n / 1_000_000).toFixed(n % 1_000_000 === 0 ? 0 : 1) + 'tr';
  }
  if (Math.abs(n) >= 1_000) {
    return Math.round(n / 1_000) + 'k';
  }
  return String(n);
}

export function formatCountdownVi(targetDate) {
  if (!targetDate) return '';
  const diffMs = targetDate.getTime() - Date.now();
  if (diffMs < 0) {
    const absMin = Math.abs(Math.round(diffMs / 60000));
    if (absMin < 60) return `Quá hạn ${absMin}p`;
    const absH = Math.round(absMin / 60);
    if (absH < 24) return `Quá hạn ${absH} giờ`;
    return `Quá hạn ${Math.round(absH / 24)} ngày`;
  }
  const mins = Math.round(diffMs / 60000);
  if (mins < 60) return `Còn ${Math.max(1, mins)} phút`;
  const hours = Math.floor(mins / 60);
  const remMins = mins % 60;
  if (hours < 24) return remMins > 0 ? `Còn ${hours}g ${remMins}p` : `Còn ${hours} giờ`;
  const days = Math.floor(hours / 24);
  const remH = hours % 24;
  return remH > 0 ? `Còn ${days} ngày ${remH}g` : `Còn ${days} ngày`;
}

export function getGreetingVi() {
  const h = new Date().getHours();
  if (h < 11) return 'Chào buổi sáng';
  if (h < 14) return 'Chào buổi trưa';
  if (h < 18) return 'Chào buổi chiều';
  return 'Chào buổi tối';
}

export function calculateStreak(completedDates = []) {
  if (!completedDates.length) return 0;
  const set = new Set(completedDates);
  const today = toDateKey(new Date());
  const yesterday = toDateKey(addDays(new Date(), -1));

  let cursor = set.has(today) ? new Date() : set.has(yesterday) ? addDays(new Date(), -1) : null;
  if (!cursor) return 0;

  let streak = 0;
  while (set.has(toDateKey(cursor))) {
    streak += 1;
    cursor = addDays(cursor, -1);
  }
  return streak;
}

