export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const key = el.getAttribute('data-icon');
    if (ICONS[key]) el.innerHTML = ICONS[key];
  });
}

/**
 * Generates and downloads an RFC 5545 .ics calendar file for a Booking/Event.
 */
export function downloadTaskICS(item) {
  if (!item || !item.date) return false;
  const start = parseDateTime(item.date, item.time || '09:00');
  if (!start) return false;
  const durationMins = Number(item.duration) || 60;
  const end = new Date(start.getTime() + durationMins * 60000);

  const fmtUtc = (d) =>
    d.getUTCFullYear().toString() +
    String(d.getUTCMonth() + 1).padStart(2, '0') +
    String(d.getUTCDate()).padStart(2, '0') +
    'T' +
    String(d.getUTCHours()).padStart(2, '0') +
    String(d.getUTCMinutes()).padStart(2, '0') +
    '00Z';

  const esc = (s) =>
    String(s || '')
      .replace(/\\/g, '\\\\')
      .replace(/;/g, '\\;')
      .replace(/,/g, '\\,')
      .replace(/\r?\n/g, '\\n');

  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//ShuShu Workspace//Booking Calendar//VI',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'BEGIN:VEVENT',
    `UID:${item.id || Date.now()}@shushu.app`,
    `DTSTAMP:${fmtUtc(new Date())}`,
    `DTSTART:${fmtUtc(start)}`,
    `DTEND:${fmtUtc(end)}`,
    `SUMMARY:${esc(item.title)}`,
    item.client ? `LOCATION:${esc(item.client)}` : null,
    `DESCRIPTION:${esc([item.client ? `Khách hàng/Địa điểm: ${item.client}` : '', item.clientPhone ? `SĐT/Zalo: ${item.clientPhone}` : '', item.notes || ''].filter(Boolean).join('\n'))}`,
    Number(item.remindBefore) >= 0 ? 'BEGIN:VALARM' : null,
    Number(item.remindBefore) >= 0 ? `TRIGGER:-PT${Math.max(1, Number(item.remindBefore) || 15)}M` : null,
    Number(item.remindBefore) >= 0 ? 'ACTION:DISPLAY' : null,
    Number(item.remindBefore) >= 0 ? `DESCRIPTION:${esc(item.title)}` : null,
    Number(item.remindBefore) >= 0 ? 'END:VALARM' : null,
    'END:VEVENT',
    'END:VCALENDAR'
  ].filter(Boolean);

  const blob = new Blob([lines.join('\r\n')], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  const slug = String(item.title || 'shushu-booking')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40) || 'booking';
  a.href = url;
  a.download = `${slug}-${item.date}.ics`;
  a.click();
  URL.revokeObjectURL(url);
  return true;
}

/**
 * Checks whether a candidate event overlaps with existing non-done items on the same day.
 */
export function findScheduleConflicts(tasks, candidate, ignoreId = null) {
  if (!candidate.date || !candidate.time) return [];
  const [ch, cm] = candidate.time.split(':').map(Number);
  if (Number.isNaN(ch) || Number.isNaN(cm)) return [];
  const startA = ch * 60 + cm;
  const endA = startA + (Number(candidate.duration) || 60);

  return (tasks || []).filter((t) => {
    if (ignoreId && t.id === ignoreId) return false;
    if (t.status === 'done') return false;
    if (t.date !== candidate.date || !t.time) return false;
    const [th, tm] = t.time.split(':').map(Number);
    if (Number.isNaN(th) || Number.isNaN(tm)) return false;
    const startB = th * 60 + tm;
    const endB = startB + (Number(t.duration) || 60);
    return startA < endB && startB < endA;
  });
}

